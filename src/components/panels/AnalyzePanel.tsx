"use client";

import { useMemo } from "react";
import { useTerritoryStore } from "@/store/useTerritoryStore";
import type { AccountView } from "@/store/selectors";
import { deterministicStrategyEngine, type StrategyMove } from "@/domain/strategy";
import { Section, Spark, StatusDot } from "../ui";
import { PanelHeader } from "./PanelHeader";

export function AnalyzePanel({ view }: { view: AccountView }) {
  const setView = useTerritoryStore((s) => s.setView);
  const prospectsById = useTerritoryStore((s) => s.prospectsById);
  const signals = useTerritoryStore((s) => s.signals);
  const focusBusinessUnit = useTerritoryStore((s) => s.focusBusinessUnit);
  const selectProspect = useTerritoryStore((s) => s.selectProspect);
  const selectOpportunity = useTerritoryStore((s) => s.selectOpportunity);

  const result = useMemo(
    () =>
      deterministicStrategyEngine.analyze({
        account: view.account,
        businessUnits: view.units.map((u) => u.unit),
        prospectsById,
        opportunities: view.opportunities,
        signals: signals.filter((s) => s.accountId === view.account.id),
      }),
    [view, prospectsById, signals],
  );

  const showProspects = (move: StrategyMove) => {
    if (move.prospectIds[0]) selectProspect(move.prospectIds[0]);
    else focusBusinessUnit(move.businessUnitId);
  };

  const focus = (move: StrategyMove) => {
    if (move.opportunityId) selectOpportunity(move.opportunityId);
    else focusBusinessUnit(move.businessUnitId);
  };

  return (
    <div className="flex flex-col gap-5">
      <PanelHeader
        eyebrow={
          <span className="inline-flex items-center gap-1.5">
            <Spark /> Analyze account
          </span>
        }
        title="Next best move"
        aside={<span className="text-[12.5px] text-paper-60">{result.summary}</span>}
        onClose={() => setView("tree")}
      />

      {result.primary ? (
        <MoveCard move={result.primary} primary prospectsById={prospectsById} onFocus={() => focus(result.primary!)} onProspects={() => showProspects(result.primary!)} onSelectProspect={selectProspect} />
      ) : (
        <p className="text-[13px] text-paper-60">No open moves. The account is fully worked or fully dormant.</p>
      )}

      {result.alternatives.length > 0 && (
        <Section title="Also worth considering">
          <ul className="flex flex-col gap-2">
            {result.alternatives.map((m) => (
              <li key={m.id}>
                <MoveCard move={m} prospectsById={prospectsById} onFocus={() => focus(m)} onProspects={() => showProspects(m)} onSelectProspect={selectProspect} />
              </li>
            ))}
          </ul>
        </Section>
      )}

      <p className="text-[11.5px] text-paper-20 leading-relaxed">
        Generated by {result.generatedBy.toLowerCase()} over local territory state. The engine interface is
        designed so a model-backed strategist can replace it without changing the interface.
      </p>
    </div>
  );
}

function MoveCard({
  move,
  primary = false,
  prospectsById,
  onFocus,
  onProspects,
  onSelectProspect,
}: {
  move: StrategyMove;
  primary?: boolean;
  prospectsById: ReturnType<typeof useTerritoryStore.getState>["prospectsById"];
  onFocus: () => void;
  onProspects: () => void;
  onSelectProspect: (id: string) => void;
}) {
  const people = move.prospectIds.map((id) => prospectsById[id]).filter(Boolean);
  return (
    <div className={`surface-quiet ${primary ? "p-4" : "p-3"} flex flex-col gap-3`}>
      <div className="flex flex-col gap-1">
        <span className="eyebrow">{KIND_LABEL[move.kind]}</span>
        <p className={`${primary ? "text-[15px]" : "text-[13.5px]"} font-medium leading-snug`}>{move.headline}</p>
      </div>

      {move.kind !== "hold" && (
        <div className="grid grid-cols-3 gap-2 text-[12px]">
          <Num label="Mapped" value={move.coverage.mapped} />
          <Num label="Contacted" value={move.coverage.contacted} />
          <Num label="Engaged" value={move.coverage.engaged} />
        </div>
      )}

      {people.length > 0 && (
        <div className="flex flex-col gap-1">
          <span className="eyebrow">{move.kind === "advance-opportunity" ? "Widen the thread" : "Recommended multithread"}</span>
          <ul className="flex flex-col -mx-1">
            {people.map((p) => (
              <li key={p.id}>
                <button type="button" className="row-btn min-h-[36px] py-1" onClick={() => onSelectProspect(p.id)}>
                  <StatusDot status={p.relationshipStatus} />
                  <span className="flex-1 min-w-0 text-[12.5px]">
                    <span className="truncate block">{p.title}</span>
                    <span className="block text-[11px] text-paper-40">{p.name} · influence {p.influence}/5</span>
                  </span>
                </button>
              </li>
            ))}
          </ul>
        </div>
      )}

      <div>
        <span className="eyebrow">Reason</span>
        <p className="text-[12.5px] text-paper-60 leading-relaxed mt-0.5">{move.reason}</p>
      </div>

      {move.kind !== "hold" && (
        <div className="flex gap-2">
          <button type="button" className={`btn btn-sm ${primary ? "btn-primary" : ""}`} onClick={onFocus}>
            {move.opportunityId ? "Open opportunity" : "Focus branch"}
          </button>
          {people.length > 0 && (
            <button type="button" className="btn btn-sm" onClick={onProspects}>
              Show prospects
            </button>
          )}
        </div>
      )}
    </div>
  );
}

const KIND_LABEL = {
  multithread: "Multithread",
  reengage: "Re-engage",
  "advance-opportunity": "Advance opportunity",
  hold: "Hold",
} as const;

function Num({ label, value }: { label: string; value: number }) {
  return (
    <div className="flex flex-col">
      <span className="eyebrow">{label}</span>
      <span className="text-[15px] font-medium tabular-nums leading-tight">{value}</span>
    </div>
  );
}
